import streamlit as st
import pandas as pd
import requests
from datetime import datetime

# =====================================================================
# НАСТРОЙКИ (Впишите свои данные)
# =====================================================================
URL_ТРЕКЕРА = "https://your-tracker-domain.com"
API_КЛЮЧ = "ВАШ_API_КЛЮЧ"

# Как называются столбцы в вашем Excel-файле Facebook
КОЛОНКА_ИМЯ_КАМПАНИИ = "Название кампании"
КОЛОНКА_РАСХОДЫ = "Потрачено (RUB)"

# =====================================================================
# ЛОГИКА ЗАПРОСА В ТРЕКЕР
# =====================================================================
def получить_доходы_из_трекера(дата):
    url = f"{URL_ТРЕКЕРА}/admin_api/v3/report/build"
    headers = {"client-key": API_КЛЮЧ, "Content-Type": "application/json"}
    
    запрос_данных = {
        "range": {"from": дата, "to": дата, "timezone": "Europe/Moscow"},
        "columns": ["campaign", "revenue"],
        "metrics": ["revenue"],
        "groupby": ["campaign"]
    }
    try:
        ответ = requests.post(url, json=запрос_данных, headers=headers)
        строки = ответ.json().get('rows', [])
        return pd.DataFrame([{"Имя_Кампании": r.get("campaign"), "Доход": float(r.get("revenue", 0))} for r in строки])
    except:
        return pd.DataFrame(columns=["Имя_Кампании", "Доход"])

# =====================================================================
# ВЕБ-ИНТЕРФЕЙС В БРАУЗЕРЕ
# =====================================================================
st.set_page_config(page_title="Калькулятор ROI", layout="wide")
st.title("📊 Анализатор расходов Facebook и Трекера")

# 1. Выбор даты (веб-календарь)
выбранная_дата = st.date_input("1. Выберите дату отчета:", datetime.now()).strftime("%Y-%m-%d")

# 2. Поле загрузки файла (Drag-and-Drop окошко)
uploaded_file = st.file_uploader("2. Перетащите сюда Excel-файл из Facebook", type=["xlsx", "xls"])

if uploaded_file is not None:
    st.success("Файл успешно загружен!")
    
    # Читаем файл, который пользователь перетащил в браузер
    таблица_фб = pd.read_excel(uploaded_file)
    
    # Проверяем колонки
    if КОЛОНКА_ИМЯ_КАМПАНИИ in таблица_фб.columns and КОЛОНКА_РАСХОДЫ in таблица_фб.columns:
        
        # Обрабатываем расходы
        таблица_фб = таблица_фб[[КОЛОНКА_ИМЯ_КАМПАНИИ, КОЛОНКА_РАСХОДЫ]].copy()
        таблица_фб.columns = ["Имя_Кампании", "Расход"]
        таблица_фб = таблица_фб.groupby("Имя_Кампании", as_index=False)["Расход"].sum().fillna(0)
        
        # Скачиваем доходы из трекера
        with st.spinner('Связываюсь с трекером...'):
            таблица_трекера = получить_доходы_из_трекера(выбранная_дата)
            
        if not таблица_трекера.empty:
            # Склеиваем данные
            итоговая_таблица = pd.merge(таблица_фб, таблица_трекера, on="Имя_Кампании", how="outer").fillna(0)
            
            # Считаем математику
            итоговая_таблица["Прибыль"] = итоговая_таблица["Доход"] - итоговая_таблица["Расход"]
            итоговая_таблица["ROI %"] = итоговая_таблица.apply(lambda r: (r["Прибыль"] / r["Расход"] * 100) if r["Расход"] > 0 else 0, axis=1)
            
            # Округляем и сортируем
            итоговая_таблица = итоговая_таблица.round(2).sort_values(by="Прибыль", ascending=False)
            
            # Выводим красивую интерактивную таблицу в браузер
            st.subheader("📋 Итоговый отчет")
            st.dataframe(итоговая_таблица, use_container_width=True)
            
            # Кнопка для скачивания готового результата обратно себе на ПК
            excel_data = итоговая_таблица.to_excel(index=False)
            st.download_button(
                label="📥 Скачать результат в Excel",
                data=uploaded_file.getvalue(), # Для простоты, или сгенерировать новый через BytesIO
                file_name=f"report_{выбранная_дата}.xlsx",
                mime="application/vnd.ms-excel"
            )
        else:
            st.error("Не удалось получить данные из трекера за эту дату.")
    else:
        st.error(f"В файле нет колонок '{КОЛОНКА_ИМЯ_КАМПАНИИ}' или '{КОЛОНКА_РАСХОДЫ}'")
